package app.gagachat.core.data.media

import android.app.NotificationManager
import android.content.Context
import android.media.AudioAttributes
import android.media.AudioManager
import android.media.Ringtone
import android.media.RingtoneManager
import android.os.SystemClock
import app.gagachat.core.data.preferences.SettingsPreferences
import app.gagachat.core.model.NotificationSoundPolicy
import dagger.hilt.android.qualifiers.ApplicationContext
import kotlinx.coroutines.CoroutineScope
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.SupervisorJob
import kotlinx.coroutines.flow.first
import kotlinx.coroutines.launch
import javax.inject.Inject
import javax.inject.Singleton

/**
 * Short foreground message sounds for an *active* chat. Unlike the Android
 * notification-channel sound, these are generated by GaGa and must check the
 * exact conversation mute plus independent direct/group preferences.
 *
 * All tone playback also respects device silent/vibrate/DND modes.
 */
@Singleton
class GagaSoundPlayer @Inject constructor(
    @ApplicationContext private val context: Context,
    private val settingsPreferences: SettingsPreferences,
) {
    private val scope = CoroutineScope(SupervisorJob() + Dispatchers.Main.immediate)
    private var current: Ringtone? = null
    private var lastToneAt = 0L

    fun playMessageSound(isGroup: Boolean, isMuted: Boolean) {
        if (isMuted) return
        scope.launch {
            val categoryEnabled = if (isGroup) settingsPreferences.groupNotificationsEnabled.first()
                else settingsPreferences.directNotificationsEnabled.first()
            val categorySoundEnabled = if (isGroup) settingsPreferences.groupMessageSoundsEnabled.first()
                else settingsPreferences.messageSoundsEnabled.first()
            if (!NotificationSoundPolicy.mayPlayMessageTone(
                    notificationsEnabled = settingsPreferences.notificationsEnabled.first(),
                    categoryEnabled = categoryEnabled,
                    soundsEnabled = categorySoundEnabled,
                    isMuted = isMuted,
                )
            ) return@launch
            playSystemNotificationTone()
        }
    }

    /** Explicit sample button; only the user can initiate it. */
    fun previewMessageSound() {
        scope.launch { playSystemNotificationTone(throttle = false) }
    }

    private fun playSystemNotificationTone(throttle: Boolean = true) {
        runCatching {
            val audio = context.getSystemService(AudioManager::class.java) ?: return@runCatching
            val notifications = context.getSystemService(NotificationManager::class.java)
            // Never circumvent silent mode or a DND rule to play a sample.
            if (audio.ringerMode != AudioManager.RINGER_MODE_NORMAL ||
                (notifications != null &&
                    notifications.currentInterruptionFilter != NotificationManager.INTERRUPTION_FILTER_ALL)
            ) return@runCatching
            val now = SystemClock.elapsedRealtime()
            if (throttle && lastToneAt != 0L && now - lastToneAt < 800L) return@runCatching
            lastToneAt = now
            current?.stop()
            val uri = RingtoneManager.getDefaultUri(RingtoneManager.TYPE_NOTIFICATION)
                ?: return@runCatching
            val ringtone = RingtoneManager.getRingtone(context, uri) ?: return@runCatching
            ringtone.audioAttributes = AudioAttributes.Builder()
                .setUsage(AudioAttributes.USAGE_NOTIFICATION)
                .setContentType(AudioAttributes.CONTENT_TYPE_SONIFICATION)
                .build()
            current = ringtone
            ringtone.play()
        }
    }
}
